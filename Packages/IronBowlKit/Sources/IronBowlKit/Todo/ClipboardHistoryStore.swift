import AppKit
import CryptoKit
import Foundation
import GRDB
import Observation

/// 剪贴板历史设置键。
public enum ClipboardKeys {
    public static let historyEnabled = SettingKey<Bool>("clipboard.enabled", default: true)
    public static let maxHistoryCount = SettingKey<Int>("clipboard.maxCount", default: 200)
}

/// 剪贴板文本内容分类。
public nonisolated enum ClipboardContentKind: String, Codable, Sendable, CaseIterable, Identifiable {
    case text
    case json
    case url
    case command
    case code

    public var id: String { rawValue }

    public var displayName: String {
        switch self {
        case .text: "文本"
        case .json: "JSON"
        case .url: "链接"
        case .command: "命令"
        case .code: "代码"
        }
    }

    public var systemImage: String {
        switch self {
        case .text: "doc.plaintext"
        case .json: "curlybraces"
        case .url: "link"
        case .command: "terminal"
        case .code: "chevron.left.forwardslash.chevron.right"
        }
    }
}

/// 剪贴板历史与常用片段数据库记录。
public nonisolated struct ClipboardHistoryItem: Sendable, Identifiable, Hashable, Codable, FetchableRecord, PersistableRecord {
    public static let databaseTableName = "clipboardHistory"

    public var id: String
    public var content: String
    public var contentHash: String
    public var kind: String
    public var sourceApp: String
    public var charCount: Int
    public var copyCount: Int
    public var isSnippet: Bool
    public var snippetTitle: String
    public var copiedAt: Date

    public init(
        id: String = UUID().uuidString,
        content: String,
        contentHash: String? = nil,
        kind: ClipboardContentKind? = nil,
        sourceApp: String = "",
        charCount: Int? = nil,
        copyCount: Int = 1,
        isSnippet: Bool = false,
        snippetTitle: String = "",
        copiedAt: Date = Date()
    ) {
        self.id = id
        self.content = content
        self.contentHash = contentHash ?? ClipboardHistoryStore.contentHash(content)
        self.kind = (kind ?? ClipboardHistoryStore.classifyKind(content)).rawValue
        self.sourceApp = sourceApp
        self.charCount = charCount ?? content.count
        self.copyCount = copyCount
        self.isSnippet = isSnippet
        self.snippetTitle = snippetTitle
        self.copiedAt = copiedAt
    }

    public var contentKind: ClipboardContentKind {
        ClipboardContentKind(rawValue: kind) ?? .text
    }

    public var displayTitle: String {
        let trimmed = snippetTitle.trimmingCharacters(in: .whitespacesAndNewlines)
        if !trimmed.isEmpty { return trimmed }
        return ScratchpadStore.derivedTitle(title: "", content: content)
    }
}

/// 剪贴板历史与常用片段库存储（含隐私类型/密码软件过滤与防循环写回）。
@Observable
public final class ClipboardHistoryStore {
    private nonisolated static let sensitivePasteboardTypes: Set<String> = [
        "org.nspasteboard.ConcealedType",
        "org.nspasteboard.TransientType",
        "org.nspasteboard.AutoGeneratedType",
        "com.agilebits.onepassword",
        "de.petermaurer.TransientPasteboardType",
    ]

    private nonisolated static let sensitiveBundleIDs: Set<String> = [
        "com.apple.keychainaccess",
        "com.apple.Passwords",
        "com.1password.1password",
        "com.agilebits.onepassword7",
        "com.bitwarden.desktop",
        "org.keepassxc.keepassxc",
    ]

    @ObservationIgnored private let database: AppDatabase
    @ObservationIgnored private let settings: SettingsStore
    @ObservationIgnored private var timer: Timer?
    @ObservationIgnored private var lastObservedChangeCount: Int
    @ObservationIgnored private var ignoredChangeCount: Int?

    public private(set) var items: [ClipboardHistoryItem] = []
    public private(set) var historyItems: [ClipboardHistoryItem] = []
    public private(set) var snippetItems: [ClipboardHistoryItem] = []

    public init(database: AppDatabase, settings: SettingsStore) {
        self.database = database
        self.settings = settings
        self.lastObservedChangeCount = NSPasteboard.general.changeCount
        reload()
    }

    isolated deinit {
        timer?.invalidate()
    }

    public func reload() {
        let fetched: [ClipboardHistoryItem] = (try? database.pool.read { db in
            guard try db.tableExists("clipboardHistory") else { return [] }
            return try ClipboardHistoryItem
                .order(Column("isSnippet").desc, Column("copiedAt").desc)
                .fetchAll(db)
        }) ?? []
        items = fetched
        var nextHistory: [ClipboardHistoryItem] = []
        var nextSnippets: [ClipboardHistoryItem] = []
        nextHistory.reserveCapacity(fetched.count)
        for item in fetched {
            if item.isSnippet {
                nextSnippets.append(item)
            } else {
                nextHistory.append(item)
            }
        }
        historyItems = nextHistory
        snippetItems = nextSnippets
    }

    // MARK: - 剪贴板监听

    public func startMonitoring() {
        guard timer == nil else { return }
        lastObservedChangeCount = NSPasteboard.general.changeCount
        timer = Timer.scheduledTimer(withTimeInterval: 1.5, repeats: true) { [weak self] _ in
            MainActor.assumeIsolated {
                self?.pollPasteboard()
            }
        }
        timer?.tolerance = 0.4
    }

    public func stopMonitoring() {
        timer?.invalidate()
        timer = nil
    }

    private func pollPasteboard() {
        let pb = NSPasteboard.general
        let currentCount = pb.changeCount
        guard currentCount != lastObservedChangeCount else { return }
        lastObservedChangeCount = currentCount

        if let ignored = ignoredChangeCount, ignored == currentCount {
            ignoredChangeCount = nil
            return
        }
        guard settings[ClipboardKeys.historyEnabled] else { return }

        let types = (pb.types ?? []).map(\.rawValue)
        let frontApp = NSWorkspace.shared.frontmostApplication
        guard !Self.shouldIgnorePasteboard(types: types, sourceBundleID: frontApp?.bundleIdentifier) else {
            return
        }
        guard let text = pb.string(forType: .string) else { return }
        let trimmed = text.trimmingCharacters(in: .whitespacesAndNewlines)
        guard !trimmed.isEmpty, text.count <= 100_000 else { return }

        let appName = frontApp?.localizedName ?? ""
        recordCopy(text, sourceApp: appName)
    }

    // MARK: - 写入与常用片段管理

    @discardableResult
    public func recordCopy(_ text: String, sourceApp: String = "", now: Date = Date()) -> ClipboardHistoryItem? {
        let trimmed = text.trimmingCharacters(in: .whitespacesAndNewlines)
        guard !trimmed.isEmpty else { return nil }
        let hash = Self.contentHash(text)
        let maxCount = max(20, settings[ClipboardKeys.maxHistoryCount])

        let saved: ClipboardHistoryItem? = try? database.pool.write { db in
            var record: ClipboardHistoryItem
            if var existing = try ClipboardHistoryItem
                .filter(Column("contentHash") == hash)
                .fetchOne(db) {
                existing.copyCount += 1
                existing.copiedAt = now
                if !sourceApp.isEmpty {
                    existing.sourceApp = sourceApp
                }
                try existing.update(db)
                record = existing
            } else {
                record = ClipboardHistoryItem(
                    content: text,
                    contentHash: hash,
                    kind: Self.classifyKind(text),
                    sourceApp: sourceApp,
                    charCount: text.count,
                    copyCount: 1,
                    isSnippet: false,
                    snippetTitle: "",
                    copiedAt: now
                )
                try record.insert(db)
            }

            // 仅裁剪非 Snippet 的历史记录，常用片段永久保留
            try db.execute(
                sql: """
                DELETE FROM clipboardHistory
                WHERE isSnippet = 0 AND id NOT IN (
                    SELECT id FROM clipboardHistory
                    WHERE isSnippet = 0
                    ORDER BY copiedAt DESC
                    LIMIT ?
                )
                """,
                arguments: [maxCount]
            )
            return record
        }
        reload()
        return saved
    }

    public func copyToPasteboard(_ text: String) {
        let pb = NSPasteboard.general
        pb.clearContents()
        pb.setString(text, forType: .string)
        ignoredChangeCount = pb.changeCount
        lastObservedChangeCount = pb.changeCount
    }

    @discardableResult
    public func saveSnippet(id: String? = nil, title: String, content: String) -> ClipboardHistoryItem? {
        let trimmedContent = content.trimmingCharacters(in: .whitespacesAndNewlines)
        guard !trimmedContent.isEmpty else { return nil }
        let cleanTitle = title.trimmingCharacters(in: .whitespacesAndNewlines)
        let hash = Self.contentHash(content)
        let now = Date()

        let saved: ClipboardHistoryItem? = try? database.pool.write { db in
            if let id, var existing = try ClipboardHistoryItem.fetchOne(db, key: id) {
                existing.snippetTitle = cleanTitle
                existing.content = content
                existing.contentHash = hash
                existing.kind = Self.classifyKind(content).rawValue
                existing.charCount = content.count
                existing.isSnippet = true
                existing.copiedAt = now
                try existing.update(db)
                return existing
            }
            if var matched = try ClipboardHistoryItem.filter(Column("contentHash") == hash).fetchOne(db) {
                matched.isSnippet = true
                matched.snippetTitle = cleanTitle
                matched.copiedAt = now
                try matched.update(db)
                return matched
            }
            let item = ClipboardHistoryItem(
                content: content,
                contentHash: hash,
                kind: Self.classifyKind(content),
                sourceApp: "手动创建",
                charCount: content.count,
                copyCount: 1,
                isSnippet: true,
                snippetTitle: cleanTitle,
                copiedAt: now
            )
            try item.insert(db)
            return item
        }
        reload()
        return saved
    }

    public func toggleSnippet(id: String, title: String? = nil) {
        try? database.pool.write { db in
            guard var item = try ClipboardHistoryItem.fetchOne(db, key: id) else { return }
            item.isSnippet.toggle()
            if let title {
                item.snippetTitle = title.trimmingCharacters(in: .whitespacesAndNewlines)
            }
            try item.update(db)
        }
        reload()
    }

    public func delete(id: String) {
        try? database.pool.write { db in
            _ = try ClipboardHistoryItem.deleteOne(db, key: id)
        }
        reload()
    }

    public func clearHistoryKeepingSnippets() {
        try? database.pool.write { db in
            try db.execute(sql: "DELETE FROM clipboardHistory WHERE isSnippet = 0")
        }
        reload()
    }

    // MARK: - 隐私过滤与分类纯函数

    public nonisolated static func shouldIgnorePasteboard(types: [String], sourceBundleID: String?) -> Bool {
        if types.contains(where: { sensitivePasteboardTypes.contains($0) }) {
            return true
        }
        if let bundle = sourceBundleID?.trimmingCharacters(in: .whitespacesAndNewlines),
           sensitiveBundleIDs.contains(bundle) {
            return true
        }
        return false
    }

    public nonisolated static func contentHash(_ text: String) -> String {
        let digest = SHA256.hash(data: Data(text.utf8))
        return digest.map { String(format: "%02x", $0) }.joined()
    }

    public nonisolated static func classifyKind(_ text: String) -> ClipboardContentKind {
        let trimmed = text.trimmingCharacters(in: .whitespacesAndNewlines)
        if (trimmed.hasPrefix("{") || trimmed.hasPrefix("[")),
           let data = trimmed.data(using: .utf8),
           (try? JSONSerialization.jsonObject(with: data, options: [.fragmentsAllowed])) != nil {
            return .json
        }
        if !trimmed.contains(where: \.isNewline),
           !trimmed.contains(" "),
           (trimmed.hasPrefix("http://") || trimmed.hasPrefix("https://")),
           URL(string: trimmed) != nil {
            return .url
        }
        let lower = trimmed.lowercased()
        let cmdPrefixes = [
            "curl ", "git ", "xcodebuild ", "swift ", "docker ", "kubectl ",
            "npm ", "pnpm ", "yarn ", "brew ", "python", "ssh ", "scp ",
            "select ", "insert ", "update ", "delete ", "$ ",
        ]
        if cmdPrefixes.contains(where: { lower.hasPrefix($0) }) {
            return .command
        }
        let codeMarkers = ["func ", "struct ", "class ", "import ", "const ", "function ", "def ", "return ", "=>"]
        if codeMarkers.contains(where: { trimmed.contains($0) }) {
            return .code
        }
        return .text
    }
}
